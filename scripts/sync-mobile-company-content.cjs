/* global __dirname, module */
// One editorial source for mobile fallback and the packaged public API. No network or database access.
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const root = path.resolve(__dirname, '..');
const ts = require(path.join(root, 'Mobile/node_modules/typescript'));
const contentDirectory = path.join(root, 'Mobile/src/features/more/data/content');
const target = path.join(root, 'Server/src/modules/company-content/data/mobile-company-content.generated.ts');

function loadEditorialContent() {
  const previous = require.extensions['.ts'];
  const allowed = new Set(['moreContent.ts', 'legalDrafts.ts', 'moreContentVersion.ts']
    .map((name) => path.join(contentDirectory, name)));
  require.extensions['.ts'] = (loaded, filename) => {
    if (!allowed.has(filename)) {
      if (previous) return previous(loaded, filename);
      throw new Error('Unexpected editorial dependency.');
    }
    const source = ts.transpileModule(fs.readFileSync(filename, 'utf8'), {
      compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2023 }, fileName: filename,
    });
    loaded._compile(source.outputText, filename);
  };
  try {
    const requireEditorial = Module.createRequire(path.join(contentDirectory, 'moreContent.ts'));
    for (const filename of allowed) delete require.cache[filename];
    const { moreContent } = requireEditorial('./moreContent.ts');
    const { MORE_CONTENT_SCHEMA_VERSION, MORE_CONTENT_REVISION } = requireEditorial('./moreContentVersion.ts');
    return { schemaVersion: MORE_CONTENT_SCHEMA_VERSION, revision: MORE_CONTENT_REVISION, content: moreContent };
  } finally {
    if (previous) require.extensions['.ts'] = previous;
    else delete require.extensions['.ts'];
  }
}

function generatedSource() {
  return '// Generated by node scripts/sync-mobile-company-content.cjs. Do not edit directly.\n'
    + '// Source: Mobile/src/features/more/data/content; no legacy database content is merged.\n'
    + '/* eslint-disable prettier/prettier */\n'
    + `export const MOBILE_COMPANY_CONTENT = ${JSON.stringify(loadEditorialContent(), null, 2)} as const;\n`;
}

if (require.main === module) {
  const expected = generatedSource();
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== expected) {
      console.error('Public mobile content is out of sync. Run node scripts/sync-mobile-company-content.cjs.');
      process.exitCode = 1;
    } else console.log('Public mobile content matches the bundled editorial source.');
  } else {
    fs.writeFileSync(target, expected, 'utf8');
    console.log('Regenerated public mobile content from the bundled editorial source.');
  }
}
module.exports = { loadEditorialContent, generatedSource };
